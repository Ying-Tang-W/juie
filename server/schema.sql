CREATE DATABASE IF NOT EXISTS image_notes CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE image_notes;
CREATE TABLE users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(80) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 avatar VARCHAR(255) NOT NULL DEFAULT '',
 avatar_path VARCHAR(255) NOT NULL DEFAULT '',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE photos (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 owner_id BIGINT UNSIGNED NOT NULL,
 title VARCHAR(255) NOT NULL,
 image_path VARCHAR(500) NOT NULL,
 is_public TINYINT(1) NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 INDEX(owner_id), INDEX(is_public),
 FOREIGN KEY(owner_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE marks (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 photo_id BIGINT UNSIGNED NOT NULL,
 x DOUBLE NOT NULL, y DOUBLE NOT NULL,
 name VARCHAR(120) NOT NULL DEFAULT '', note TEXT NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(photo_id) REFERENCES photos(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE user_settings (
 user_id BIGINT UNSIGNED PRIMARY KEY,
 settings_json JSON NOT NULL,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
